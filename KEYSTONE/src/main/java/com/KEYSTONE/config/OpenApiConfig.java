package com.KEYSTONE.config;

import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Contact;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.info.License;
import io.swagger.v3.oas.models.security.SecurityRequirement;
import io.swagger.v3.oas.models.security.SecurityScheme;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

@Configuration
public class OpenApiConfig {

    @Bean
    public OpenAPI customOpenAPI() {
        final String securitySchemeName = "BearerAuth";
        return new OpenAPI()
                .info(new Info()
                        .title("Project KEYSTONE - Field Service Management Platform API")
                        .version("1.0.0")
                        .description("RESTful API services for Meridian Facilities Management. Supports 4 RBAC roles (Manager, Dispatcher, Technician, Customer) across Work Order Lifecycle, SLAs, Parts Inventory, and Analytics.")
                        .contact(new Contact().name("Keystone Engineering Team").email("engineering@keystone.com"))
                        .license(new License().name("Proprietary - Zidio Development Engineering Project")))
                .addSecurityItem(new SecurityRequirement().addList(securitySchemeName))
                .components(new Components()
                        .addSecuritySchemes(securitySchemeName,
                                new SecurityScheme()
                                        .name(securitySchemeName)
                                        .type(SecurityScheme.Type.HTTP)
                                        .scheme("bearer")
                                        .bearerFormat("JWT")));
    }
}
